// Package runtime defines the proposed boundary for a future real executor.
// It is not connected to the current simulated worker or HTTP server.
package runtime

import (
	"context"
	"errors"
	"regexp"
)

// Provider errors are fixed categories. Implementations must not expose provider
// response bodies or request values through errors, logs, or result structures.
var (
	ErrInvalid        = errors.New("runtime: invalid request")
	ErrConflict       = errors.New("runtime: operation conflicts with existing resource")
	ErrNotFound       = errors.New("runtime: resource not found")
	ErrUnavailable    = errors.New("runtime: provider unavailable")
	ErrCancelled      = errors.New("runtime: operation cancelled")
	ErrTimeout        = errors.New("runtime: operation timed out")
	ErrUnknownOutcome = errors.New("runtime: operation outcome unknown")
)

// Identity scopes an operation to a service and installation. IDs must be
// generated by Dársena, not supplied directly by an untrusted client.
type Identity struct {
	Installation string
	Service      string
	Operation    string
}

// Spec identifies immutable desired input. Configuration values are deliberately
// excluded until revision-aware secret injection is designed and implemented.
type Spec struct {
	Identity Identity
	Image    string // Locally available image pinned by SHA-256 digest.
	Revision uint64 // Revision identity only; this does not imply it was applied.
}

// Ref is an opaque provider identifier scoped to its complete owner identity.
// A provider may use a deterministic name rather than its daemon's resource ID
// so that a caller can inspect after a lost create response.
type Ref struct {
	Identity   Identity
	ResourceID string
	// Fingerprint binds the reference to immutable input and provider policy.
	Fingerprint string
	Image       string
	Revision    uint64
}

type State string

const (
	StateCreated State = "created"
	StateRunning State = "running"
	StateStopped State = "stopped"
)

// Result contains only observed non-sensitive state. On a known partial create,
// Create returns the known reference together with an error. A zero result on
// ErrUnknownOutcome must not be interpreted as proof that no effect occurred.
type Result struct {
	Ref   Ref
	State State
	// ExitCode is the process exit status of a stopped resource, when known.
	ExitCode *int
}

// Runtime must verify complete ownership before inspecting or mutating a resource.
// Create repeats safely for the same operation and immutable spec; a different
// spec conflicts. A repeat returns the observed state; it must not implicitly
// restart a stopped resource or retry a partial start. Stop is repeatable. Remove is repeatable for absent resources,
// but rejects running resources. A cancellation after dispatch can have an
// unknown outcome; callers must reconcile rather than retry blindly.
type Runtime interface {
	Create(context.Context, Spec) (Result, error)
	Inspect(context.Context, Ref) (Result, error)
	Stop(context.Context, Ref) (Result, error)
	Remove(context.Context, Ref) error
}

var (
	idPattern       = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,62}$`)
	resourcePattern = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,127}$`)
	// Image names are deliberately limited; credentials, whitespace, tags and
	// arbitrary URL syntax are not accepted in this first contract.
	imagePattern = regexp.MustCompile(`^[a-z0-9]+(?:[._/-][a-z0-9]+)*(?::[0-9]+)?/[a-z0-9]+(?:[._/-][a-z0-9]+)*@sha256:[a-f0-9]{64}$`)
)

// Validate checks the provider-independent boundary and returns a fixed error.
func (s Spec) Validate() error {
	if !s.Identity.Valid() || len(s.Image) > 512 || !imagePattern.MatchString(s.Image) || s.Revision == 0 {
		return ErrInvalid
	}
	return nil
}

// Valid reports whether all scope identifiers have safe, bounded syntax.
func (i Identity) Valid() bool {
	return idPattern.MatchString(i.Installation) && idPattern.MatchString(i.Service) && idPattern.MatchString(i.Operation)
}

// Valid reports whether a reference can safely be used for provider lookup.
// Providers must additionally verify ownership against observed provider data.
func (r Ref) Valid() bool {
	return r.Identity.Valid() && resourcePattern.MatchString(r.ResourceID)
}
